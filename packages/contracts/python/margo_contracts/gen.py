"""Generate margo_contracts/models.py from the local database schema (`uv run gen-models`).

Run after every migration, with `pnpm db:types` for the TypeScript side. Reads only the local
Supabase stack, whose connection string is a public default (D44).
"""

from __future__ import annotations

import os
from pathlib import Path

# Override with MARGO_LOCAL_DB_URL when a worktree runs its own stack on other ports.
LOCAL_DB_URL = os.environ.get("MARGO_LOCAL_DB_URL", "postgresql://postgres:postgres@127.0.0.1:54322/postgres")
MODELS_PATH = Path(__file__).with_name("models.py")

SCALARS = {
    "uuid": "UUID",
    "text": "str",
    "varchar": "str",
    "bpchar": "str",
    "citext": "str",
    "inet": "str",
    "bool": "bool",
    "int2": "int",
    "int4": "int",
    "int8": "int",
    "numeric": "Decimal",
    "float8": "float",
    "date": "date",
    "timestamptz": "datetime",
    "timestamp": "datetime",
    "json": "JsonValue",
    "jsonb": "JsonValue",
}

HEADER = '''\
"""Generated by `uv run gen-models` from supabase/migrations. Do not edit."""

from datetime import date, datetime
from decimal import Decimal
from enum import StrEnum
from uuid import UUID

from pydantic import BaseModel, ConfigDict, JsonValue


class Row(BaseModel):
    model_config = ConfigDict(frozen=True)
'''

# table, column, data_type, udt_name, is_nullable
Column = tuple[str, str, str, str, bool]


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def py_type(udt: str, enums: dict[str, list[str]]) -> str:
    if udt.startswith("_"):
        return f"list[{py_type(udt[1:], enums)}]"
    if udt in enums:
        return pascal(udt)
    return SCALARS[udt]


def render(columns: list[Column], enums: dict[str, list[str]]) -> str:
    out = [HEADER]
    for name in sorted(enums):
        out.append(f"\nclass {pascal(name)}(StrEnum):")
        out.extend(f'    {v.upper()} = "{v}"' for v in enums[name])
        out.append("")
    tables: dict[str, list[Column]] = {}
    for col in sorted(columns):
        tables.setdefault(col[0], []).append(col)
    for table, cols in tables.items():
        out.append(f"\nclass {pascal(table)}(Row):")
        for _, column, _, udt, nullable in cols:
            t = py_type(udt, enums)
            out.append(f"    {column}: {t} | None" if nullable else f"    {column}: {t}")
        out.append("")
    return "\n".join(out)


def generate(db_url: str = LOCAL_DB_URL) -> str:
    import psycopg

    with psycopg.connect(db_url) as conn:
        columns = [
            (t, c, dt, udt, nullable == "YES")
            for t, c, dt, udt, nullable in conn.execute(
                """
                select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable
                from information_schema.columns c
                join information_schema.tables t
                  on t.table_schema = c.table_schema and t.table_name = c.table_name
                where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
                """
            )
        ]
        enums: dict[str, list[str]] = {}
        for name, label in conn.execute(
            """
            select t.typname, e.enumlabel from pg_type t
            join pg_enum e on e.enumtypid = t.oid
            join pg_namespace n on n.oid = t.typnamespace
            where n.nspname = 'public' order by t.typname, e.enumsortorder
            """
        ):
            enums.setdefault(name, []).append(label)
    # Column order follows the sorted names, so output does not depend on migration order.
    return render(columns, enums)


def main() -> None:
    MODELS_PATH.write_text(generate())
    print(f"gen-models: wrote {MODELS_PATH}")
