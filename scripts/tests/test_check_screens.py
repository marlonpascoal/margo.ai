"""F01: every design/*.dc.html has an entry in 05-screens and a route or template in the code."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import check_screens  # noqa: E402

REPO = Path(__file__).resolve().parents[2]

SPEC = """\
Shared components: `design/Menu.dc.html` (console sidebar). Flow map is `design/Main.dc.html`.

### C00. Login do console
- **Route** `/console/login` · **Who** invited staff e-mails.

### C03. Vizinhança de 3 km (step 2)
- **Route** `/console/raio-x/[id]/vizinhanca`.

### P15 / W06. Entrar
- **Route** `/entrar` · **Who** anyone.

### P04. Extensão do Chrome (popup)
- **Where** `extension/`, popup on the Partner Portal tab.

### P10. Pagamento (Asaas hosted checkout)
- Not built by us.

| Code | What | Generated by | Done when |
|---|---|---|---|
| P01 | Raio-X PDF | worker-render | numbers match |

| Code | What | Flag |
|---|---|---|
| L01 | Painel do dono | `l.painel_dono` |

Keep the routes reserved (`/app/painel`, `/app/cupom/[id]`).
"""

DESIGN = [
    "C00-Login",
    "C03-Vizinhanca",
    "P15-Entrar",
    "W06-Entrar",
    "P04-Extensao",
    "P10-Pagamento",
    "P01-RaioXPDF",
    "L01-Painel",
    "Menu",
    "Main",
]


def make_repo(tmp: Path, pages: list[str], files: list[str] = (), pending: str = "") -> Path:
    (tmp / "spec").mkdir()
    (tmp / "spec" / "05-screens.md").write_text(SPEC)
    (tmp / "design").mkdir()
    for name in DESIGN:
        (tmp / "design" / f"{name}.dc.html").write_text("<html></html>")
    for route in pages:
        p = tmp / "apps/web/app" / route.strip("/") / "page.tsx"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("export default function Page() { return null }\n")
    for f in files:
        p = tmp / f
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("x")
    (tmp / "scripts").mkdir(exist_ok=True)
    (tmp / "scripts" / "screens_pending.txt").write_text(pending)
    return tmp


ALL_PAGES = ["console/login", "(console)/console/raio-x/[id]/vizinhanca", "(owner)/entrar"]
ALL_FILES = [
    "extension/src/popup/P04-popup.tsx",
    "workers/render/templates/P01-raio-x.html",
    "apps/web/components/Menu.tsx",
]


def test_F01_passes_when_every_screen_is_specified_and_built(tmp_path: Path) -> None:
    root = make_repo(tmp_path, ALL_PAGES + ["app/painel"], ALL_FILES)
    assert check_screens.check(root) == []


def test_F01_route_groups_do_not_count_as_path_segments(tmp_path: Path) -> None:
    root = make_repo(tmp_path, ALL_PAGES + ["(owner)/(reserved)/app/painel"], ALL_FILES)
    assert check_screens.check(root) == []


def test_F01_design_file_without_spec_entry_fails(tmp_path: Path) -> None:
    root = make_repo(tmp_path, ALL_PAGES + ["app/painel"], ALL_FILES)
    (root / "design" / "C99-Nova.dc.html").write_text("")
    assert check_screens.check(root) == ["C99: design/C99-Nova.dc.html has no entry in spec/05-screens.md"]


def test_F01_spec_code_listed_twice_fails(tmp_path: Path) -> None:
    root = make_repo(tmp_path, ALL_PAGES + ["app/painel"], ALL_FILES)
    spec = root / "spec" / "05-screens.md"
    spec.write_text(spec.read_text() + "\n### C00. Login de novo\n- **Route** `/console/login`.\n")
    assert check_screens.check(root) == ["C00: listed 2 times in spec/05-screens.md, expected once"]


def test_F01_missing_route_fails_unless_pending(tmp_path: Path) -> None:
    root = make_repo(tmp_path, ["console/login", "(owner)/entrar", "app/painel"], ALL_FILES)
    assert check_screens.check(root) == [
        "C03: no page for route /console/raio-x/[id]/vizinhanca (or list it in scripts/screens_pending.txt)"
    ]
    (root / "scripts" / "screens_pending.txt").write_text("# wave 1\nC03  # lane A\n")
    assert check_screens.check(root) == []


def test_F01_pending_screen_that_is_built_fails_as_stale(tmp_path: Path) -> None:
    root = make_repo(tmp_path, ALL_PAGES + ["app/painel"], ALL_FILES, pending="C00\n")
    assert check_screens.check(root) == ["C00: built but still listed in scripts/screens_pending.txt"]


def test_F01_documents_and_extension_need_a_template_file(tmp_path: Path) -> None:
    root = make_repo(tmp_path, ALL_PAGES + ["app/painel"], ["apps/web/components/Menu.tsx"])
    assert check_screens.check(root) == [
        "P01: no template file named P01* in apps/, workers/ or extension/ (or list it in scripts/screens_pending.txt)",
        "P04: no template file named P04* in apps/, workers/ or extension/ (or list it in scripts/screens_pending.txt)",
    ]


def test_F01_reserved_after_feb_screens_need_their_reserved_route(tmp_path: Path) -> None:
    root = make_repo(tmp_path, ALL_PAGES, ALL_FILES)
    assert check_screens.check(root) == [
        "L01: no page for route /app/painel (or list it in scripts/screens_pending.txt)"
    ]


def test_F01_real_design_folder_is_fully_covered_by_the_spec() -> None:
    errors = [e for e in check_screens.check(REPO) if "spec/05-screens.md" in e]
    assert errors == []
