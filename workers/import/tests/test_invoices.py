def zip_bytes() -> bytes:
    return ZIP.read_bytes()


def one_xml() -> bytes:
    with zipfile.ZipFile(io.BytesIO(zip_bytes())) as zf:
        name = next(n for n in zf.namelist() if n.endswith("-nfe.xml"))
        return zf.read(name)


def cnpj_dv_ok(c: str) -> bool:
    def dv(digits: str, weights: list[int]) -> int:
        r = sum(int(d) * w for d, w in zip(digits, weights, strict=True)) % 11
        return 0 if r < 2 else 11 - r

    d1 = dv(c[:12], [5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2])
    d2 = dv(c[:12] + str(d1), [6, 5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2])
    return c[12:] == f"{d1}{d2}"


# Keys -------------------------------------------------------------------------------------------------


def test_D01_access_key_check_digit_mod_11() -> None:
    first43 = "4126101234567800019055001000001234112345678"
    assert key_check_digit(first43) == 6, "same digit as app.nfe_access_key_valid"
    assert key_valid(first43 + "6")
    assert not key_valid(first43 + "7"), "wrong check digit"
    assert not key_valid(first43), "43 digits"
    assert not key_valid(first43 + "x")


def test_D01_typed_key_and_qr_link_give_the_key() -> None:
    key = "4126101234567800019065001000001234112345678"
    key += str(key_check_digit(key))
    spaced = " ".join(key[i : i + 4] for i in range(0, 44, 4))
    assert key_from_input(spaced) == (key, "key_typed"), "the placeholder groups digits by 4"
    qr = f"https://www.fazenda.pr.gov.br/nfce/qrcode?p={key}|2|1|1|ABCDEF0123456789"
    assert key_from_input(qr) == (key, "qr_url")


def test_D01_invalid_key_rejected() -> None:
    key = "4126101234567800019065001000001234112345678"
    bad = key + str((key_check_digit(key) + 1) % 10)
    assert key_from_input(bad) is None
    assert key_from_input(f"https://www.fazenda.pr.gov.br/nfce/qrcode?p={bad}|2|1|1|X") is None
    assert key_from_input("https://www.fazenda.pr.gov.br/nfce/qrcode?chave=1") is None
    model_57 = "4126101234567800019057001000001234112345678"
    assert key_from_input(model_57 + str(key_check_digit(model_57))) is None, "only NF-e 55 and NFC-e 65"


