pytestmark_db = pytest.mark.skipif(not DB_TESTS, reason="MARGO_DB_TESTS=1 runs it against the local stack")


@pytest.fixture
def conn() -> Iterator[Any]:
    import psycopg
    from margo_import import db

    c = db.connect()
    try:
        with c.transaction():
            yield c
            raise psycopg.Rollback()
    finally:
        c.close()


def new_import(conn: Any, account: str = "G-01", path: str = "invoices/t/notas.zip") -> str:
    return str(
        conn.execute(
            """insert into public.invoice_import (account_id, file_path, file_name)
               select id, %s, 'notas.zip' from public.account where code = %s returning id""",
            (path, account),
        ).fetchone()["id"]
    )


def forget_fixture_invoices(conn: Any) -> None:
    """Start from an account without the zip's invoices (the seed may already hold them)."""
    keys = [i.access_key for i in read_zip(zip_bytes()).invoices]
    conn.execute("delete from public.invoice where access_key = any(%s)", (keys,))


@pytestmark_db
def test_D01_zip_import_counts_dedupe_and_reimport(conn: Any) -> None:
    from margo_common.files import MemoryFileStore
    from margo_import.invoice_run import process_invoice_zip

    forget_fixture_invoices(conn)
    files = MemoryFileStore({"invoices/t/notas.zip": zip_bytes()})
    run = new_import(conn)
    out = process_invoice_zip(conn, files, run)
    assert (out.status, out.reason) == ("ok", None)
    r = conn.execute("select * from public.invoice_import where id = %s", (run,)).fetchone()
    assert (r["invoices_new"], r["months_count"], r["suppliers_count"]) == (312, 12, 41)
    assert (r["nfe_count"], r["nfce_count"], r["duplicates"], r["rejected"]) == (268, 44, 9, 0)
    n = conn.execute(
        "select count(*) as n from public.invoice where invoice_import_id = %s", (run,)
    ).fetchone()["n"]
    assert n == 312
    stored = [p for p in files.files if p.endswith(".xml")]
    assert len(stored) == 312 and all(p.startswith("invoices/") for p in stored)

    again = new_import(conn)
    assert process_invoice_zip(conn, files, again).status == "ok"
    r2 = conn.execute("select * from public.invoice_import where id = %s", (again,)).fetchone()
    assert (r2["invoices_new"], r2["duplicates"]) == (0, 321), "every file is a duplicate the second time"


@pytestmark_db
def test_D01_C06_real_account_without_authorization_is_refused(conn: Any) -> None:
    from margo_common.files import MemoryFileStore
    from margo_import.invoice_run import process_invoice_zip

    forget_fixture_invoices(conn)
    conn.execute("update public.account set is_synthetic = false where code = 'G-01'")
    files = MemoryFileStore({"invoices/t/notas.zip": zip_bytes()})
    run = new_import(conn)
    out = process_invoice_zip(conn, files, run)
    assert (out.status, out.reason) == ("failed", "no_owner_authorization"), (
        "G-01 authorized iFood, not notas"
    )
    assert (
        conn.execute(
            "select count(*) as n from public.invoice where invoice_import_id = %s", (run,)
        ).fetchone()["n"]
        == 0
    )
    assert not [p for p in files.files if p.endswith(".xml")], "nothing stored"


