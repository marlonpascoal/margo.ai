def test_D01_xml_zip_counts_as_drawn_in_C10() -> None:
    read = read_zip(zip_bytes())
    stats = zip_stats(read.invoices, read.duplicates_in_zip)
    # C10: "312 notas · 12 meses · 41 fornecedores / NF-e: 268 · NFC-e: 44 · duplicadas: 9"
    assert (stats.invoices, stats.months, stats.suppliers) == (312, 12, 41)
    assert (stats.nfe, stats.nfce, stats.duplicates) == (268, 44, 9)
    assert read.files_total == 321 and read.skipped == {}


def test_D01_fixture_is_synthetic() -> None:
    read = read_zip(zip_bytes())
    assert all(not cnpj_dv_ok(i.issuer_cnpj) for i in read.invoices), "issuer CNPJs never valid"
    assert all(key_valid(i.access_key) for i in read.invoices)
    assert all("SINTÉTICO" in (i.issuer_name or "") for i in read.invoices)
    assert "SINTETICO" in ZIP.name


def test_D01_lines_of_an_invoice() -> None:
    read = read_zip(zip_bytes())
    carne = next(i for i in read.invoices if any(li.description.startswith("CARNE BOV") for li in i.lines))
    li = carne.lines[0] if carne.lines[0].description.startswith("CARNE") else carne.lines[1]
    assert (li.ncm, li.gtin, li.unit, li.unit_price_cents) == ("02013000", None, "KG", 3890)
    assert li.total_cents == int(li.qty * 3890)
    assert [x.line_no for x in carne.lines] == list(range(1, len(carne.lines) + 1))
    refri = next(i for i in read.invoices if i.model == 65 and any("COCA" in x.description for x in i.lines))
    assert refri.buyer_cnpj is None, "an NFC-e names no buyer"
    assert all(x.gtin and len(x.gtin) == 13 for x in refri.lines if "LT 350ML" in x.description)


def test_D01_invalid_key_in_xml_is_rejected() -> None:
    xml = one_xml()
    key = xml.split(b'Id="NFe', 1)[1][:44].decode()
    broken = key[:43] + str((int(key[43]) + 1) % 10)
    with pytest.raises(InvoiceError) as e:
        parse_xml(xml.replace(key.encode(), broken.encode()))
    assert e.value.reason == "invalid_key"


def test_D01_other_files_are_skipped_with_a_reason() -> None:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr("a.xml", one_xml())
        zf.writestr("evento.xml", b'<procEventoNFe xmlns="http://www.portalfiscal.inf.br/nfe"/>')
        zf.writestr("quebrado.xml", b"<nfeProc")
        zf.writestr("x.xml", b'<!DOCTYPE x [<!ENTITY a "a">]><x/>')
        zf.writestr("leia.txt", b"oi")
    read = read_zip(buf.getvalue())
    assert len(read.invoices) == 1
    assert read.skipped == {"not_invoice": 2, "unreadable": 1}
    with pytest.raises(InvoiceError):
        read_zip(b"not a zip")


def test_D01_line_discount_lowers_the_line_total() -> None:
    xml = one_xml().replace(b"</vProd><cEANTrib>", b"</vProd><vDesc>1.00</vDesc><cEANTrib>", 1)
    inv, orig = parse_xml(xml), parse_xml(one_xml())
    assert inv.lines[0].total_cents == orig.lines[0].total_cents - 100
    assert inv.lines[0].qty == orig.lines[0].qty and isinstance(inv.lines[0].qty, Decimal)


